import { fileURLToPath } from 'node:url';
import type { NextConfig } from 'next';
import createNextIntlPlugin from 'next-intl/plugin';

// The monorepo keeps one .env at the root so web, worker and the Prisma CLI
// cannot drift onto different databases. Next only looks inside the app
// directory, so load it here, before anything reads process.env.
try {
  process.loadEnvFile(fileURLToPath(new URL('../../.env', import.meta.url)));
} catch {
  // Absent in CI, where variables are injected directly.
}

const withNextIntl = createNextIntlPlugin('./src/i18n/request.ts');

/**
 * Content Security Policy.
 *
 * Written out rather than pulled from a helper because every directive here is
 * a decision about what an archive application is allowed to do, and a reader
 * auditing this file should be able to see all of them at once.
 *
 * `'unsafe-eval'` is permitted in development only: Turbopack's HMR runtime
 * needs it. Production gets no eval.
 */
function contentSecurityPolicy(isDev: boolean): string {
  const directives: Record<string, string[]> = {
    'default-src': ["'self'"],
    // 'unsafe-inline' for scripts is required by Next's inlined bootstrap.
    // A nonce-based policy is the follow-up; see docs/SECURITY.md.
    'script-src': ["'self'", "'unsafe-inline'", ...(isDev ? ["'unsafe-eval'"] : [])],
    // Styles are generated by Tailwind at build time, but Next inlines a
    // critical block, and MapLibre sets inline styles on its canvas container.
    'style-src': ["'self'", "'unsafe-inline'"],
    'img-src': ["'self'", 'data:', 'blob:', 'https:'],
    'font-src': ["'self'", 'data:'],
    // blob: is needed for MapLibre's web workers.
    'worker-src': ["'self'", 'blob:'],
    'connect-src': ["'self'", ...(isDev ? ['ws:', 'wss:'] : [])],
    'media-src': ["'self'", 'blob:', 'data:'],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'self'"],
    // Nobody frames a private family archive.
    'frame-ancestors': ["'none'"],
    'upgrade-insecure-requests': [],
  };

  return Object.entries(directives)
    .map(([key, values]) => (values.length ? `${key} ${values.join(' ')}` : key))
    .join('; ');
}

const isDev = process.env.NODE_ENV === 'development';

const config: NextConfig = {
  reactStrictMode: true,

  // Next offers to write its own CLAUDE.md / AGENTS.md into this directory.
  // The repository already has one at the root that covers the whole monorepo,
  // and a second, framework-scoped file would compete with it.
  agentRules: false,

  // Workspace packages ship TypeScript source rather than a build step, which
  // keeps the edit-run loop instant across the monorepo.
  transpilePackages: [
    '@chronolignee/ui',
    '@chronolignee/engine',
    '@chronolignee/domain',
    '@chronolignee/genealogy',
    '@chronolignee/db',
    '@chronolignee/config',
  ],

  experimental: {
    // Prisma's driver adapter and pg must stay on the Node runtime.
    serverActions: { bodySizeLimit: '8mb' },
  },

  serverExternalPackages: ['@prisma/client', 'pg', 'pino'],

  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'Content-Security-Policy', value: contentSecurityPolicy(isDev) },
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'X-Frame-Options', value: 'DENY' },
          {
            key: 'Permissions-Policy',
            value: 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
          },
          ...(isDev
            ? []
            : [
                {
                  key: 'Strict-Transport-Security',
                  value: 'max-age=63072000; includeSubDomains; preload',
                },
              ]),
        ],
      },
    ];
  },
};

export default withNextIntl(config);
