/**
 * Writes the SQL that installs the historical catalogue.
 *
 * The catalogue lives in TypeScript (src/history/catalogue.ts), where dates
 * are written as genealogists write them and parsed by the domain; the
 * migration is generated from it so the Julian days in the database are
 * exactly the ones the application computes. Idempotent: an entry already
 * present by title is left alone, so re-running a seed or a migration never
 * duplicates the Second World War.
 *
 * Usage: tsx scripts/historical-catalogue-sql.ts > prisma/migrations/<dir>/migration.sql
 */
import { parseGenealogicalDate } from '@chronolignee/domain';
import { HISTORICAL_CATALOGUE } from '../src/history/catalogue';

const quote = (value: string) => `'${value.replace(/'/g, "''")}'`;
const array = (values: readonly string[]) =>
  values.length === 0 ? "'{}'::text[]" : `ARRAY[${values.map(quote).join(', ')}]::text[]`;

const lines: string[] = [
  '-- The shared historical catalogue (generated by scripts/historical-catalogue-sql.ts).',
  '-- Installed for every tree, not only the demonstration. Idempotent by title.',
  '',
  '-- The demonstration seeded one title with a straight apostrophe before the',
  '-- catalogue existed; renamed to the catalogue spelling so it is not doubled.',
  `UPDATE "historical_events" SET "title" = 'Grande vague d’immigration européenne en Argentine'`,
  `WHERE "title" = 'Grande vague d''immigration européenne en Argentine'`,
  `  AND NOT EXISTS (SELECT 1 FROM "historical_events" WHERE "title" = 'Grande vague d’immigration européenne en Argentine');`,
  '',
];

for (const entry of HISTORICAL_CATALOGUE) {
  const start = parseGenealogicalDate(entry.start).interval.earliest;
  const end = parseGenealogicalDate(entry.end).interval.latest;
  if (start === null || end === null || end < start) {
    throw new Error(`unreadable or reversed dates for ${entry.title}`);
  }
  lines.push(
    `INSERT INTO "historical_events" ("title", "summary", "category", "significance", "startJdn", "endJdn", "countryCodes", "regionLabels", "locale", "updatedAt")`,
    `SELECT ${quote(entry.title)}, ${quote(entry.summary)}, ${quote(entry.category)}::"HistoricalEventCategory", ${entry.significance}, ${start}, ${end}, ${array(entry.countryCodes)}, ${array(entry.regionLabels ?? [])}, 'fr', CURRENT_TIMESTAMP`,
    `WHERE NOT EXISTS (SELECT 1 FROM "historical_events" WHERE "title" = ${quote(entry.title)});`,
    // An entry already there (seeded before the catalogue) takes the
    // catalogue's dates and words: the catalogue is the reference.
    `UPDATE "historical_events" SET "summary" = ${quote(entry.summary)}, "category" = ${quote(entry.category)}::"HistoricalEventCategory", "significance" = ${entry.significance}, "startJdn" = ${start}, "endJdn" = ${end}, "countryCodes" = ${array(entry.countryCodes)}, "regionLabels" = ${array(entry.regionLabels ?? [])}, "updatedAt" = CURRENT_TIMESTAMP`,
    `WHERE "title" = ${quote(entry.title)};`,
  );
}

process.stdout.write(`${lines.join('\n')}\n`);
